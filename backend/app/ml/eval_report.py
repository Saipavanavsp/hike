"""Render docs/evaluation.md from the evaluation result files.

Every number in the report is read from app/ml/eval_holdout_results.json and
app/ml/eval_results.json; the wording that compares methods is chosen from the confidence
intervals, so the report cannot claim a difference the data does not support.
"""

import json
from pathlib import Path

SYNTHETIC_PATH = Path(__file__).parent / "eval_results.json"
NAMES = {"tfidf": "TF-IDF", "minilm": "MiniLM (embeddings only)", "hike": "Hike hybrid score"}
LAYOUTS = {
    "pdf_classic": "PDF, one column",
    "pdf_two_column": "PDF, two columns",
    "docx_table": "DOCX, table layout",
    "docx_caps": "DOCX, all-caps headings",
}
CATEGORIES = {
    "backend": "Backend",
    "frontend": "Frontend",
    "fullstack": "Full stack",
    "data_ml": "Data / ML",
    "devops": "DevOps",
    "mobile": "Mobile",
    "qa": "QA",
    "other": "Other (embedded)",
}


def _ci(m: dict) -> str:
    return f"{m['mean']:.3f} ({m['ci95'][0]:.2f} to {m['ci95'][1]:.2f})"


def _verdict(diff: dict, other: str) -> str:
    lo, hi = diff["ci95"]
    sign = "+" if diff["mean"] >= 0 else ""
    text = f"{sign}{diff['mean']:.3f} (95% CI {lo:+.3f} to {hi:+.3f})"
    if lo > 0:
        return f"{text}: Hike is better than {other} on this data."
    if hi < 0:
        return f"{text}: {other} is better than Hike on this data."
    return f"{text}: the interval includes zero, so there is no clear difference."


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def render(h: dict) -> str:
    syn = json.loads(SYNTHETIC_PATH.read_text(encoding="utf-8"))
    d = h["dataset"]
    m = h["methods"]
    diffs = h["paired_differences"]
    inv = h["format_invariance"]
    lines: list[str] = []
    add = lines.append

    add("# Matching evaluation")
    add("")
    add(
        "_Generated by `python -m app.ml.eval_holdout --report` from "
        "`backend/app/ml/eval_holdout_results.json` and `backend/app/ml/eval_results.json`. "
        "Do not edit by hand._"
    )
    add("")
    add("## Summary")
    add("")
    add(
        f"- On the holdout set ({d['resumes']} resumes x {d['jobs']} jobs, every resume read "
        f"from a PDF or DOCX by the production parser), the Hike hybrid score reaches NDCG@5 "
        f"{m['hike']['ndcg_at_5']['mean']:.3f}, TF-IDF {m['tfidf']['ndcg_at_5']['mean']:.3f} "
        f"and MiniLM alone {m['minilm']['ndcg_at_5']['mean']:.3f}."
    )
    add(f"- Hike vs TF-IDF, NDCG@5: {_verdict(diffs['hike_minus_tfidf']['ndcg_at_5'], 'TF-IDF')}")
    add(f"- Hike vs MiniLM, NDCG@5: {_verdict(diffs['hike_minus_minilm']['ndcg_at_5'], 'MiniLM')}")
    two_col = h["parser_by_format"]["pdf_two_column"]
    add(
        f"- The weakest layout is the two-column PDF: the parser found the candidate's name in "
        f"{_pct(two_col['name_ok'])} of them and missed total experience by "
        f"{two_col['years_abs_error']:.1f} years on average, because text extraction "
        f"interleaves the columns."
    )
    add(
        f"- The same resume rendered in four layouts moves its match scores by "
        f"{inv['mean_score_spread_points']:.1f} points (out of 100) on average, and keeps "
        f"{_pct(inv['top5_overlap_vs_first_layout'])} of its top-5 jobs."
    )
    add(
        "- These numbers come from a small, hand-written dataset with AI-drafted labels. They "
        "are evidence that the pipeline works end to end and where it is fragile, not a "
        "measurement of real-world hiring quality. See Limitations."
    )
    add("")

    add("## What was evaluated")
    add("")
    add("Two separate datasets, both fictional:")
    add("")
    add(
        f"1. **Synthetic seed set**: {syn['matching']['n_resumes']} resumes x "
        f"{syn['matching']['n_jobs']} jobs generated by `seed/build_seed_data.py`, with labels "
        "from a rule (same role category and experience within range). The system was "
        "developed against this data, so it is not a fair test on its own."
    )
    add(
        f"2. **Holdout set** (`backend/eval/holdout`): {d['resumes']} resumes and {d['jobs']} jobs "
        f"written by hand, independent of the seed generator, including "
        f"{d['distractor_jobs']} non-software distractor jobs (sales engineer, business analyst, "
        "firmware, Salesforce, technical writer, data entry). Resumes vary in wording "
        '("k8s", "Postgres", "ReactJS"), seniority (intern to staff), and include a career '
        "changer and an off-target embedded engineer. Each is rendered in one of four layouts "
        "and parsed by the production parser."
    )
    add("")
    add(
        f"Holdout labels are graded: {d['strong_pairs']} strong fits (2), {d['partial_pairs']} "
        f"partial fits (1), and 0 for the other "
        f"{d['pairs'] - d['strong_pairs'] - d['partial_pairs']} pairs. The rubric:"
    )
    add("")
    rubric = json.loads(
        (Path(__file__).resolve().parents[2] / "eval" / "holdout" / "labels.json").read_text(
            encoding="utf-8"
        )
    )
    for grade in ("2", "1", "0"):
        add(f"- **{grade}**: {rubric['rubric'][grade]}")
    add(f"- Adjacent role families: {rubric['rubric']['adjacent_families']}.")
    add("")
    add(f"Label provenance: {rubric['provenance']}")
    add("")
    add("Metrics, per resume then averaged (95% bootstrap intervals over resumes):")
    add("")
    add(
        "- **P@5 / R@5**: share of the top 5 that is relevant (grade >= 1) / share of relevant jobs found in the top 5."
    )
    add("- **MRR**: 1 / rank of the first relevant job.")
    add("- **NDCG@5**: ranking quality with graded gains (2^grade - 1), 1.0 = ideal order.")
    add("")

    add("## Holdout results")
    add("")
    add("| Method | P@5 | R@5 | MRR | NDCG@5 |")
    add("|---|---|---|---|---|")
    for key, name in NAMES.items():
        r = m[key]
        add(
            f"| {name} | {_ci(r['p_at_5'])} | {_ci(r['r_at_5'])} | {_ci(r['mrr'])} | "
            f"{_ci(r['ndcg_at_5'])} |"
        )
    add("")
    add(
        f"Most resumes have fewer than five acceptable jobs, so the best possible P@5 on this "
        f"set is {d['oracle_p_at_5']:.3f}. MRR is 1.0 for every method: each one ranks an "
        "acceptable job first for every resume, so this set is too easy to separate methods "
        "at rank 1."
    )
    add("")
    add("Paired differences (Hike minus baseline, same resumes):")
    add("")
    add("| Comparison | P@5 | NDCG@5 |")
    add("|---|---|---|")
    for key, label in (
        ("hike_minus_tfidf", "Hike - TF-IDF"),
        ("hike_minus_minilm", "Hike - MiniLM"),
    ):
        p = diffs[key]["p_at_5"]
        n = diffs[key]["ndcg_at_5"]
        add(
            f"| {label} | {p['mean']:+.3f} ({p['ci95'][0]:+.3f} to {p['ci95'][1]:+.3f}) | "
            f"{n['mean']:+.3f} ({n['ci95'][0]:+.3f} to {n['ci95'][1]:+.3f}) |"
        )
    add("")
    dist = h["distractors_in_top5"]
    add(
        "Share of top-5 slots taken by non-software distractor jobs (software resumes only): "
        + ", ".join(f"{NAMES[k]} {_pct(v)}" for k, v in dist.items())
        + "."
    )
    add("")

    add("### By role category")
    add("")
    add("NDCG@5 per category (n = resumes; small groups, read as indicative only).")
    add("")
    add("| Category | n | TF-IDF | MiniLM | Hike |")
    add("|---|---|---|---|---|")
    for cat, row in h["by_category"].items():
        add(
            f"| {CATEGORIES.get(cat, cat)} | {row['n']} | {row['tfidf']['ndcg_at_5']:.3f} | "
            f"{row['minilm']['ndcg_at_5']:.3f} | {row['hike']['ndcg_at_5']:.3f} |"
        )
    add("")

    add("### By document layout")
    add("")
    add(
        "| Layout | n | Hike NDCG@5 | Hike P@5 | Skill recall | Skill precision | Years error | Name found | Location found |"
    )
    add("|---|---|---|---|---|---|---|---|---|")
    for fmt, label in LAYOUTS.items():
        row = h["by_format"][fmt]
        p = h["parser_by_format"][fmt]
        add(
            f"| {label} | {row['n']} | {row['hike']['ndcg_at_5']:.3f} | "
            f"{row['hike']['p_at_5']:.3f} | {_pct(p['skill_recall'])} | "
            f"{_pct(p['skill_precision'])} | {p['years_abs_error']:.1f} yrs | "
            f"{_pct(p['name_ok'])} | {_pct(p['location_ok'])} |"
        )
    add("")
    add(
        "Each layout holds different resumes with different numbers of acceptable jobs, so "
        "P@5 and NDCG@5 differences between rows mostly reflect content, not layout; the "
        "format-invariance test below holds content fixed. The parser columns are the "
        "layout-specific signal."
    )
    add("")
    add(
        f"Skill recall is measured against each resume's hand-listed skills that exist in the "
        f"taxonomy ({_pct(h['taxonomy_coverage'])} of listed skills do). Precision counts any "
        "extracted skill not on the hand list as wrong, including more specific ones "
        '("Amazon S3" when the list says "AWS"), so it understates real precision.'
    )
    add("")

    add("### Format invariance")
    add("")
    add(
        f"{inv['resumes']} resumes were rendered in all four layouts and scored against all jobs. "
        f"Mean spread of a (resume, job) score across layouts: "
        f"{inv['mean_score_spread_points']:.2f} points (worst resume "
        f"{inv['max_score_spread_points']:.2f}). Top-5 overlap with the first layout: "
        f"{_pct(inv['top5_overlap_vs_first_layout'])}. Experience-years error by layout: "
        + ", ".join(
            f"{LAYOUTS[k]} {v:.1f} yrs" for k, v in inv["years_abs_error_by_layout"].items()
        )
        + "."
    )
    add("")
    add(
        "Two-column layouts are the main source of format bias: candidates who use them get "
        "a less accurate experience figure, which feeds the experience component of the "
        "score. The review screen asks every seeker to confirm or correct the parsed years "
        "and skills before matching, which is the mitigation in the product today."
    )
    add("")

    add("## Synthetic seed set")
    add("")
    add("| Method | P@5 | R@5 | MRR | NDCG@5 | Accuracy |")
    add("|---|---|---|---|---|---|")
    syn_names = {
        "tfidf": "TF-IDF",
        "embeddings": "MiniLM (embeddings only)",
        "hike": "Hike hybrid score",
    }
    for key, name in syn_names.items():
        r = syn["matching"]["methods"][key]
        add(
            f"| {name} | {r['precision_at_5']:.3f} | {r['recall_at_5']:.3f} | {r['mrr']:.3f} | "
            f"{r.get('ndcg_at_5', float('nan')):.3f} | {r['accuracy']:.3f} |"
        )
    add("")
    add(
        f"{syn['matching']['n_relevant_pairs']} relevant pairs out of "
        f"{syn['matching']['n_resumes'] * syn['matching']['n_jobs']}. TF-IDF does best here: "
        "the synthetic resumes and jobs come from the same templates and share vocabulary."
    )
    add("")
    c = syn["classifier"]
    add(
        f"Role classifier: {c['cv_synthetic']['accuracy']:.3f} accuracy in 5-fold "
        f"cross-validation on {c['cv_synthetic']['n']} synthetic samples, and "
        f"{c['seed_resumes']['accuracy']:.3f} on the {c['seed_resumes']['n']} seed resumes. "
        "Both sets are synthetic and easy; this does not predict accuracy on real resumes."
    )
    add("")

    add("## Limitations")
    add("")
    add(
        "- **No real resumes.** Every resume and job is fictional and written for this project. Real resumes are longer, messier and more varied."
    )
    add(
        "- **Labels are not independent.** They were drafted with AI assistance using the rubric above and have not been checked by a second labeller, so there is no inter-annotator agreement figure."
    )
    add(
        "- **The rubric favours skill overlap.** Grades depend partly on listed-skill overlap, and the Hike score has a skill-overlap component, which flatters Hike relative to the baselines."
    )
    add(
        "- **Small sample.** 24 resumes give wide confidence intervals; category rows have 1-4 resumes each."
    )
    add("- **Ceiling effects.** MRR is 1.0 for every method, and NDCG@5 is near its ceiling.")
    add(
        "- **No demographic fairness test.** The data has no consented demographic attributes, so this report covers format robustness only, not bias across candidate groups."
    )
    add("")
    add("## What a real-world evaluation would need")
    add("")
    add(
        "1. Consented, anonymised resumes and job posts (names, contacts and photos removed before labelling)."
    )
    add(
        "2. At least two independent labellers per pair, the rubric above, and Cohen's kappa reported."
    )
    add("3. A few hundred resumes, stratified by role, seniority and layout.")
    add("4. Outcome labels where available (shortlisted / interviewed) alongside judged relevance.")
    add("")
    add(
        "The harness already supports this: put the files in `backend/eval/holdout`, export pairs with `--export-labels`, collect grades, import them with `--import-labels`, and rerun with `--report`."
    )
    add("")
    add("## Reproduce")
    add("")
    add("```powershell")
    add("cd backend")
    add(
        "python -m eval.holdout.build            # re-render the holdout documents (dev dependency: reportlab)"
    )
    add("python -m app.ml.eval                   # synthetic set -> app/ml/eval_results.json")
    add(
        "python -m app.ml.eval_holdout --report  # holdout set -> app/ml/eval_holdout_results.json + this file"
    )
    add("```")
    add("")
    return "\n".join(lines)
